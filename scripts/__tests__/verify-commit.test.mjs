import test from "node:test";
import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "verify-commit.mjs");
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "verify-commit-"));
test.after(() => fs.rmSync(tmp, { recursive: true, force: true }));

let n = 0;
/** Run the script in hook mode against a message file. */
function check(msg) {
  const file = path.join(tmp, `msg-${n++}.txt`);
  fs.writeFileSync(file, msg);
  const r = spawnSync(process.execPath, [SCRIPT, file], { encoding: "utf8" });
  return { ok: r.status === 0, out: r.stdout + r.stderr };
}
const ok = (msg) => {
  const r = check(msg);
  assert.equal(r.ok, true, `expected accept: ${JSON.stringify(msg)}\n${r.out}`);
};
const bad = (msg) => assert.equal(check(msg).ok, false, `expected reject: ${JSON.stringify(msg)}`);

const CMS_TRAILERS =
  "\n\nAuthored-by: @octo-cat <octo-cat@users.noreply.github.com>\nApproved-by: @boss <boss@users.noreply.github.com> (superadmin)";

test("allowed tags are accepted", () => {
  for (const t of ["feat", "fix", "chore", "docs", "refactor", "style", "test", "security", "draft"]) {
    ok(`${t}: do a thing`);
    ok(`${t}(scope.x_y-z): do a thing`);
  }
});

test("invalid tags are rejected", () => {
  bad("WIP: x");
  bad("Yolo(core): x");
  bad("FEAT: x");
  bad("feature: x");
  bad("feat:x");
  bad("just some words");
});

test("word limit: 24 words ok, 25 rejected", () => {
  const subject = (count) => "feat: " + Array(count - 1).fill("w").join(" "); // "feat:" is word 1
  assert.equal(subject(24).split(/\s+/).length, 24);
  ok(subject(24));
  assert.equal(subject(25).split(/\s+/).length, 25);
  bad(subject(25));
});

test("CMS-style subjects containing bot/gemini/claude words are accepted", () => {
  ok("feat(ai-ml): add building-a-discord-bot article [skip vercel]");
  ok("feat(ai-ml): Gemini API basics (#30)");
  ok("feat(ai-ml): Claude prompting tips (#31)");
  ok("fix: handle bot detection in middleware");
});

test("CMS squash merge with Authored-by/Approved-by trailers is accepted", () => {
  ok("feat(ai-ml): Building a Discord Bot with Gemini (#42)" + CMS_TRAILERS);
});

test("explicit AI attribution in subject is rejected", () => {
  bad("feat: x generated by Claude");
  bad("fix: thing written with ChatGPT");
  bad("chore: stuff made using an AI");
  bad("feat: add page \u{1F916}");
});

test("AI trailers are rejected", () => {
  bad("feat: x\n\nCo-authored-by: Claude <claude@anthropic.com>");
  bad("feat: x\n\nCo-authored-by: Real Person <real@gmail.com>\nCo-authored-by: Copilot <c@example.com>");
  bad("feat: x\n\nAuthored-by: @gemini-bot <gemini-bot@users.noreply.github.com>");
});

test("Co-authored-by: real email accepted, noreply/bot rejected", () => {
  ok("feat: x\n\nCo-authored-by: Real Person <real.person@ssn.edu.in>");
  bad("feat: x\n\nCo-authored-by: Someone <12345+someone@users.noreply.github.com>");
  bad("feat: x\n\nCo-authored-by: Someone <noreply@example.com>");
  bad("feat: x\n\nCo-authored-by: Someone <deploy@example.com>\nrandom trailer line");
});

test("CMS draft branch commit is accepted", () => {
  ok("draft(club): update wip draft x [skip vercel]");
  ok("draft(ai-ml): update wip draft building-a-discord-bot [skip vercel]");
});

test("revert commits are exempt from subject rules but not trailer rules", () => {
  ok('Revert "feat: something"\n\nThis reverts commit 0123456789abcdef.');
  bad('Revert "x"\n\nCo-authored-by: Claude <c@anthropic.com>');
});

test("hook mode ignores git template comments and merge subjects", () => {
  ok("feat: real subject\n\n# Please enter the commit message\n# lines starting with # are ignored");
  ok("Merge branch 'main' into feature");
});

// ---------------------------------------------------------------------------
// Range mode, on a throwaway repo under the OS temp dir
// ---------------------------------------------------------------------------
const repo = path.join(tmp, "repo");
fs.mkdirSync(repo);
function git(...args) {
  return execFileSync("git", args, {
    cwd: repo,
    encoding: "utf8",
    env: {
      ...process.env,
      GIT_AUTHOR_NAME: "T",
      GIT_AUTHOR_EMAIL: "t@example.com",
      GIT_COMMITTER_NAME: "T",
      GIT_COMMITTER_EMAIL: "t@example.com",
    },
  }).trim();
}
function commit(file, msg) {
  fs.writeFileSync(path.join(repo, file), file + Math.random());
  git("add", file);
  git("-c", "commit.gpgsign=false", "commit", "-q", "-m", msg);
  return git("rev-parse", "HEAD");
}
function run(args) {
  const res = spawnSync(process.execPath, [SCRIPT, ...args], { cwd: repo, encoding: "utf8" });
  return { ok: res.status === 0, out: res.stdout + res.stderr };
}

test("range mode: checks every non-merge commit and skips true merges", () => {
  git("init", "-q", "-b", "main");
  const base = commit("a.txt", "chore: base");
  git("checkout", "-q", "-b", "side");
  commit("b.txt", "feat: good side commit");
  git("checkout", "-q", "main");
  commit("c.txt", "fix: good main commit");
  git("-c", "commit.gpgsign=false", "merge", "-q", "--no-ff", "side", "-m", "Merge branch side into main with a non conforming message");
  const head = git("rev-parse", "HEAD");
  assert.equal(git("rev-list", "--parents", "-n", "1", "HEAD").split(" ").length, 3, "HEAD is a merge commit");

  const good = run(["--range", `${base}..${head}`]);
  assert.equal(good.ok, true, good.out);
  assert.match(good.out, /merge commit skipped/);
  assert.match(good.out, /Checked 2 commit\(s\)/);

  // A bad commit that is NOT the tip must still fail the range.
  git("checkout", "-q", "-b", "bad", head);
  const badSha = commit("d.txt", "WIP: sloppy");
  commit("e.txt", "feat: good tip commit");
  const res = run(["--range", `${head}..bad`]);
  assert.equal(res.ok, false, "bad commit that is not the tip must fail the range");
  assert.ok(res.out.includes(badSha), "report names the offending commit");
  assert.match(res.out, /Checked 2 commit\(s\).*1 violation/);

  // Checking only the tip (what the old CI did) would have passed.
  assert.equal(run(["--range", "bad~1..bad"]).ok, true);
});

test("range mode: bad range and missing value fail", () => {
  assert.equal(run(["--range", "nonexistent..alsonot"]).ok, false);
  assert.equal(run(["--range"]).ok, false);
});

test("no-arg mode verifies HEAD and skips a merge HEAD", () => {
  git("checkout", "-q", "main");
  assert.equal(run([]).ok, true, "HEAD is the non conforming merge commit");
  commit("f.txt", "oops not a tag");
  assert.equal(run([]).ok, false);
});

test("CMS self-publish trailer: Superadmins and Heads only, own noreply address", () => {
  ok("feat(ai-ml): Post (#5)\n\nAuthored-by: @h1 <h1@users.noreply.github.com>\nSelf-published-by: @h1 <h1@users.noreply.github.com> (vertical_head)");
  ok("feat(ai-ml): Post (#5)\n\nAuthored-by: @sa1 <sa1@users.noreply.github.com>\nSelf-published-by: @sa1 <sa1@users.noreply.github.com> (superadmin)");
  bad("feat(ai-ml): Post (#5)\n\nAuthored-by: @d1 <d1@users.noreply.github.com>\nSelf-published-by: @d1 <d1@users.noreply.github.com> (deputy)");
  bad("feat(ai-ml): Post (#5)\n\nSelf-published-by: @h1 <someone-else@users.noreply.github.com> (vertical_head)");
});

